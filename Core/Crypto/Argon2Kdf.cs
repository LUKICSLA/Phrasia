using System.Security.Cryptography;
using System.Text;
using Konscious.Security.Cryptography;

namespace Phrasia;

/// <summary>
/// Argon2id (RFC 9106) via the Konscious.Security.Cryptography.Argon2 library (MIT).
///
/// Before first use a self-test runs against known-answer vectors computed by the reference
/// argon2-cffi implementation (the official Argon2 C library). If the library computed differently,
/// <see cref="IsAvailable"/> returns false and Phrasia stays on the vetted PBKDF2 (format v3).
/// </summary>
internal static class Argon2Kdf
{
    private static readonly Lazy<bool> SelfTest = new(RunSelfTest, isThreadSafe: true);

    /// <summary>True if Argon2id passed the self-test and may be used.</summary>
    public static bool IsAvailable => SelfTest.Value;

    /// <summary>Self-test result for logging / diagnostics.</summary>
    public static string? SelfTestError { get; private set; }

    /// <summary>Derives key material. The password is UTF-8 encoded and the working buffer is zeroed afterwards.</summary>
    public static byte[] Derive(string password, byte[] salt, int memoryKiB, int passes, int lanes, int length)
    {
        var pw = Encoding.UTF8.GetBytes(password);
        try
        {
            return DeriveRaw(pw, salt, memoryKiB, passes, lanes, length);
        }
        finally
        {
            CryptographicOperations.ZeroMemory(pw);
        }
    }

    /// <summary>Runs Argon2id over raw password bytes with the given parameters and returns the requested length.</summary>
    private static byte[] DeriveRaw(byte[] password, byte[] salt, int memoryKiB, int passes, int lanes, int length)
    {
        using var argon2 = new Argon2id(password)
        {
            Salt = salt,
            MemorySize = memoryKiB,
            Iterations = passes,
            DegreeOfParallelism = lanes
        };
        return argon2.GetBytes(length);
    }

    // Known-answer test vectors generated by the reference argon2-cffi 25.1.0 implementation
    // (Argon2id, version 0x13). They cover 1, 2 and 4 lanes and 1 and 3 passes.
    private static readonly (string Password, string Salt, int Passes, int MemoryKiB, int Lanes, string Hash)[] Vectors =
    {
        ("f811d2750b77414f1093e12db89a82f82caf42787ec911b44f136e4095bd5a2e4bd7c077acff54b0",
         "384c461e60f92abc9706f0c6b2a42084", 1, 256, 4,
         "35dce4f1a62cece6dbed0e330b9382121ce5cd45c50637a425c4b4f5e660cf44"),
        ("f3fa1c4a7c12c3fb846321c13b48a62ebe0f2fc69cbbc9c15bdb4ede477fdc3cad415dc4dd",
         "e969e6be8e26391fcb6d1750377a8085b116e3c96058454fda2e3d832b580ebb", 1, 8, 1,
         "c383f0a3c6d8b118663f43cb918d9a71f47f189d33936b19236d4fd27589b38b"),
        ("eb2f5794282f9e1dc4656d18147c",
         "e94c089c9080ef3bb4450d17875298bf24945690e88c1c1e3e38a55217d3d603", 3, 16, 2,
         "a1e4db74519802b525922102bc2fefc7ba4c8f6f33a5bc7509ba9f28680bd060")
    };

    /// <summary>Verifies Argon2id against the known-answer vectors; returns false (and sets the error) on mismatch.</summary>
    private static bool RunSelfTest()
    {
        try
        {
            foreach (var v in Vectors)
            {
                var expected = Convert.FromHexString(v.Hash);
                var actual = DeriveRaw(Convert.FromHexString(v.Password), Convert.FromHexString(v.Salt),
                                       v.MemoryKiB, v.Passes, v.Lanes, expected.Length);
                if (!CryptographicOperations.FixedTimeEquals(actual, expected))
                {
                    SelfTestError = $"Argon2id self-test failed (t={v.Passes}, m={v.MemoryKiB}, p={v.Lanes})";
                    return false;
                }
            }
            return true;
        }
        catch (Exception ex)
        {
            SelfTestError = "Argon2id self-test error: " + ex.Message;
            return false;
        }
    }
}
